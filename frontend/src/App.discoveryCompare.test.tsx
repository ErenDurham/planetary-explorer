import { afterEach, expect, it, vi } from "vitest";
import { fireEvent,render,screen } from "@testing-library/react";
import { QueryClient,QueryClientProvider } from "@tanstack/react-query";
import { useAppStore } from "@/store/useAppStore";
import { useDiscoveryStore } from "@/features/discovery/store/useDiscoveryStore";
import { useRegionTarget } from "@/features/regions/store";
import type { RegionTarget } from "@/features/regions/model";
vi.mock("@/features/regions/RegionWorkspace",()=>({RegionWorkspace:({target}:{target:RegionTarget})=><div data-testid="compared-target">{target.kind}:{target.runId}:{target.id}</div>}));
vi.mock("@/features/discovery",()=>({DiscoveryView:()=> <div>Found candidate selected</div>}));
vi.mock("@/components/globe/PlanetViewer",()=>({PlanetViewer:()=>null}));
import App from "./App";
afterEach(()=>{vi.restoreAllMocks();useRegionTarget.setState(useRegionTarget.getInitialState(),true);useDiscoveryStore.setState(useDiscoveryStore.getInitialState(),true);});
it("Advanced Compare carries the selected found candidate even after a previous catalog comparison",()=>{
 vi.spyOn(globalThis,"fetch").mockResolvedValue(new Response(JSON.stringify({error:{code:"unavailable",message:"No other data needed"}}),{status:503}));
 useAppStore.setState({...useAppStore.getInitialState(),activeTab:"explore",exploreMode:"find_analogs"},true);
 useDiscoveryStore.getState().setRun("real-survey");useDiscoveryStore.getState().selectCandidate("region-03-03");
 useRegionTarget.getState().open({kind:"catalog",id:"atacama_yungay"});
 render(<QueryClientProvider client={new QueryClient({defaultOptions:{queries:{retry:false}}})}><App/></QueryClientProvider>);
 fireEvent.click(screen.getByTestId("advanced-nav"));
 fireEvent.click(screen.getByRole("menuitem",{name:/^Compare/}));
 expect(screen.getByTestId("compared-target")).toHaveTextContent("discovered:real-survey:region-03-03");
 expect(useRegionTarget.getState().target?.id).not.toBe("atacama_yungay");
});
